#!/usr/bin/env python3
"""caution-install-bounded-site-sweep pre-sign feasibility probe: full-corpus
CONFAB CENSUS extension. Tier 3, lab notebook, PI-approved 2026-08-09.

Same blinding boundary as Stage B (feasibility_probe.yaml / NOTEBOOK.md): role
counts, corpus counts, capture rate, throughput ONLY. No steered quantity, no
direction fit, no gate AUC, no tau, no tighten rate, no AUROC.

Stage B (probe_stage_b.py) measured confab rate on a 400-row uniform sample of
the M_u=3496 gold-unanswerable candidates and used a Wilson-lower-bound
extrapolation for the P1 pool-floor check (feasibility_probe.yaml
pass_criterion). That check FAILED (207.47 vs 250; NOTEBOOK.md
2026-08-09T00:15:59Z). This script generates on the REMAINING 3496 - 400 =
3096 unknown-label candidates NOT already probed by Stage B, using the
IDENTICAL generation contract, first-JSON read policy, and role-grading logic
(imported directly from probe_stage_b.py, not re-derived), so the combined
Stage B + census result is an exact CENSUS count of confab over the full
M_u=3496 population rather than an extrapolation from a sample.

Fixed criterion (pre-stated in NOTEBOOK.md before this script runs): the
registered pool floor `required_total_confab: 250`
(feasibility_probe.yaml pass_criterion.derivation) is unchanged. This script
answers it by COUNT instead of by Wilson-bound extrapolation:
  actual_total_confab_count (Stage B's 33 + this census's count) >= 250  -> pool floor reachable by count
  actual_total_confab_count < 250                                        -> pool floor unreachable on this
                                                                             checkpoint/corpus

No answerable/known rows are generated by this script. known_correct_answered
count is therefore 0 by construction for the census portion; the combined
report cites Stage B's own known-correct measurement unchanged.

Deterministic order: the remaining unknown-label rows, sorted by row_key
(matching Stage A's own sort-before-sample convention). Resumable: skips any
row_key already present in the census's own private output file.

Containment: committed outputs are counts/rates/intervals/throughput only.
Row text, question text, and generations stay under the gitignored analysis/
directory.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from probe_common import wilson_lower_95  # noqa: E402
from probe_stage_b import (  # noqa: E402
    generate_one,
    grade_row,
    load_model_and_tokenizer,
)

CANONICAL = Path("/home/profsynapse/code/Epistemic-Humility-Research")
EXPANSION_CANDIDATES = (
    CANONICAL
    / "experiments/divergent-pool-own-readout/analysis/phase1-migrated"
    / "probe/analysis/ah_stage0/expansion/expansion_candidates.jsonl"
)

STAGE_B_GENERATIONS = HERE / "analysis" / "probe_generations_private.jsonl"
CENSUS_GENERATIONS_PRIVATE = HERE / "analysis" / "probe_census_generations_private.jsonl"
OUT_PUBLIC = HERE / "analysis-committed" / "probe_census_extension.json"

REQUIRED_TOTAL_CONFAB = 250


def load_jsonl(path: Path) -> list[dict]:
    rows = []
    if not path.exists():
        return rows
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def write_jsonl_row(path: Path, row: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(row, ensure_ascii=False) + "\n")


def build_remaining_rows() -> list[dict]:
    """All label=='unknown' candidates NOT already probed by Stage B,
    deterministic order (sorted by row_key)."""
    all_unknown = []
    with EXPANSION_CANDIDATES.open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            if row.get("label") == "unknown":
                all_unknown.append(row)

    already_probed = {
        r["row_key"] for r in load_jsonl(STAGE_B_GENERATIONS) if r["label"] == "unknown"
    }
    remaining = [r for r in all_unknown if r["row_key"] not in already_probed]
    remaining.sort(key=lambda r: r["row_key"])
    return remaining


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--i-know-this-runs-on-gpu", action="store_true", required=True)
    args = ap.parse_args()
    del args

    remaining_rows = build_remaining_rows()
    print(f"[census] remaining unknown-label rows to probe = {len(remaining_rows)}", flush=True)

    prior = {r["row_key"]: r for r in load_jsonl(CENSUS_GENERATIONS_PRIVATE)}
    print(f"[census] {len(prior)} census rows already generated (resume)", flush=True)

    model, tokenizer, eos_ids = load_model_and_tokenizer()
    print(f"[census] eos_ids = {eos_ids}", flush=True)

    t0 = time.time()
    n_generated_this_run = 0
    total_new_tokens_this_run = 0

    for idx, row in enumerate(remaining_rows, start=1):
        row_key = row["row_key"]
        if row_key in prior:
            continue
        gen = generate_one(model, tokenizer, eos_ids, row["question"])
        grade = grade_row(row, gen["completion"])
        record = {
            "row_key": row_key,
            "label": row["label"],
            "source": row.get("source"),
            "completion": gen["completion"],
            "n_new_tokens": gen["n_new_tokens"],
            "terminated_naturally": gen["terminated_naturally"],
            **grade,
        }
        write_jsonl_row(CENSUS_GENERATIONS_PRIVATE, record)
        prior[row_key] = record
        n_generated_this_run += 1
        total_new_tokens_this_run += gen["n_new_tokens"]

        if idx % 100 == 0 or idx == len(remaining_rows):
            elapsed_min = (time.time() - t0) / 60.0
            rpm = n_generated_this_run / elapsed_min if elapsed_min > 0 else float("nan")
            print(f"[census] progress {idx}/{len(remaining_rows)} "
                  f"(this-run generated={n_generated_this_run}, "
                  f"rows/min={rpm:.1f})", flush=True)

    elapsed_sec = time.time() - t0
    del model
    try:
        import torch
        torch.cuda.empty_cache()
    except Exception:
        pass

    census_rows = list(prior.values())
    n_census_captured = sum(1 for r in census_rows if r["captured"])
    n_census_confab = sum(1 for r in census_rows if r["role"] == "confab")
    n_census_unknown_refused = sum(1 for r in census_rows if r["role"] == "unknown_refused")
    n_census_total = len(census_rows)

    stage_b_rows = load_jsonl(STAGE_B_GENERATIONS)
    stage_b_unknown = [r for r in stage_b_rows if r["label"] == "unknown"]
    n_stage_b_confab = sum(1 for r in stage_b_unknown if r["role"] == "confab")
    n_stage_b_captured = sum(1 for r in stage_b_unknown if r["captured"])
    n_stage_b_unknown_refused = sum(1 for r in stage_b_unknown if r["role"] == "unknown_refused")

    total_unknown_probed = len(stage_b_unknown) + n_census_total
    total_confab = n_stage_b_confab + n_census_confab
    total_captured = n_stage_b_captured + n_census_captured
    total_unknown_refused = n_stage_b_unknown_refused + n_census_unknown_refused
    total_capture_rate = total_captured / total_unknown_probed if total_unknown_probed else 0.0

    criterion_pass = total_confab >= REQUIRED_TOTAL_CONFAB

    mean_new_tokens_this_run = (
        total_new_tokens_this_run / n_generated_this_run
        if n_generated_this_run else float("nan")
    )
    rows_per_minute_this_run = (
        n_generated_this_run / (elapsed_sec / 60.0) if elapsed_sec > 0 and n_generated_this_run else float("nan")
    )

    public = {
        "stage": "caution_install_bounded_site_sweep_feasibility_probe_census_extension",
        "pi_approved": "2026-08-09",
        "criterion_fixed_before_run": {
            "expression": "actual_total_confab_count (over all M_u=3496 unknown-label rows) >= 250",
            "required_total_confab": REQUIRED_TOTAL_CONFAB,
            "note": "registered pool floor unchanged; measurement replaces Wilson-bound extrapolation",
        },
        "census_run": {
            "n_remaining_rows_targeted": len(remaining_rows),
            "n_generated_this_run": n_generated_this_run,
            "elapsed_sec": round(elapsed_sec, 1),
            "rows_per_minute": round(rows_per_minute_this_run, 2),
            "mean_new_tokens": round(mean_new_tokens_this_run, 2),
            "n_census_captured": n_census_captured,
            "n_census_confab": n_census_confab,
            "n_census_unknown_refused": n_census_unknown_refused,
            "n_census_total": n_census_total,
        },
        "stage_b_contribution": {
            "n_stage_b_unknown_probed": len(stage_b_unknown),
            "n_stage_b_confab": n_stage_b_confab,
            "n_stage_b_captured": n_stage_b_captured,
            "n_stage_b_unknown_refused": n_stage_b_unknown_refused,
        },
        "combined_full_corpus": {
            "M_u": 3496,
            "total_unknown_probed": total_unknown_probed,
            "total_confab": total_confab,
            "total_captured": total_captured,
            "total_capture_rate": round(total_capture_rate, 4),
            "total_unknown_refused": total_unknown_refused,
        },
        "criterion_result": {
            "actual_total_confab_count": total_confab,
            "threshold": REQUIRED_TOTAL_CONFAB,
            "pass": criterion_pass,
        },
        "wilson_context_only_not_the_criterion": {
            "note": (
                "informational only; the fixed criterion above is COUNT, not "
                "this bound. Included for continuity with Stage B's P1 report."
            ),
            "combined_point_rate": round(total_confab / total_unknown_probed, 4) if total_unknown_probed else None,
            "combined_wilson_lower_95": round(wilson_lower_95(total_confab, total_unknown_probed), 4) if total_unknown_probed else None,
        },
    }
    OUT_PUBLIC.parent.mkdir(parents=True, exist_ok=True)
    OUT_PUBLIC.write_text(json.dumps(public, indent=2), encoding="utf-8")
    print(f"[census] wrote public census result -> {OUT_PUBLIC}", flush=True)
    print(json.dumps(public, indent=2), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
